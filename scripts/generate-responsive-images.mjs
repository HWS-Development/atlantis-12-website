import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { dirname, join, relative, sep } from "node:path";
import sharp from "sharp";

const SOURCE_ROOT = join(process.cwd(), "public/images");
const OUTPUT_ROOT = join(process.cwd(), "public/responsive-images");
const MANIFEST_PATH = join(process.cwd(), "src/generated/responsive-images.js");
const PHOTO_WIDTHS = [480, 800, 1200, 1600];
const LOGO_WIDTHS = [64, 128, 256, 384, 480, 800];

async function collectFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((entry) => {
      const path = join(directory, entry.name);
      return entry.isDirectory() ? collectFiles(path) : [path];
    }),
  );
  return files.flat();
}

await rm(OUTPUT_ROOT, { recursive: true, force: true });

const files = (await collectFiles(SOURCE_ROOT)).filter(
  (file) => /\.(?:png|webp)$/.test(file) && !file.includes(`${sep}photo-selection${sep}`),
);
const manifest = {};
let generatedCount = 0;

for (const file of files) {
  const metadata = await sharp(file).metadata();
  const sourceWidth = metadata.width;
  const sourceHeight = metadata.height;
  if (!sourceWidth || !sourceHeight) continue;

  const relativePath = relative(SOURCE_ROOT, file).split(sep).join("/");
  const sourceUrl = `/images/${relativePath}`;
  const sources = [];
  const isPng = file.endsWith(".png");
  const widths = isPng ? LOGO_WIDTHS : PHOTO_WIDTHS;

  for (const width of widths.filter((candidate) => candidate < sourceWidth)) {
    const outputFile = join(OUTPUT_ROOT, String(width), relativePath);
    await mkdir(dirname(outputFile), { recursive: true });
    const image = sharp(file).resize({ width, withoutEnlargement: true });
    await (isPng
      ? image.png({ compressionLevel: 9, adaptiveFiltering: true })
      : image.webp({ quality: 78, effort: 4 })
    ).toFile(outputFile);
    sources.push({ src: `/responsive-images/${width}/${relativePath}`, width });
    generatedCount += 1;
  }

  manifest[sourceUrl] = {
    width: sourceWidth,
    height: sourceHeight,
    sources,
  };
}

await mkdir(dirname(MANIFEST_PATH), { recursive: true });
await writeFile(
  MANIFEST_PATH,
  `// Generated by scripts/generate-responsive-images.mjs\nexport default ${JSON.stringify(manifest, null, 2)};\n`,
);

console.log(`Generated ${generatedCount} responsive variants for ${files.length} images.`);
